"""Pydantic schemas for Faculty AI Review Assistant.

Defines input context for reviewing student solution pods and structured output contracts.
"""

import uuid
from typing import Literal
from pydantic import BaseModel, ConfigDict, Field


class ProjectUpdateSummary(BaseModel):
    """Summarized student milestone update for AI review context."""

    title: str
    content: str
    prototype_url: str | None = None
    created_at: str

    model_config = ConfigDict(extra="ignore")


class ProjectReviewSummary(BaseModel):
    """Previous faculty review feedback for historical context."""

    reviewer_name: str | None = None
    decision: str
    feedback_text: str
    created_at: str

    model_config = ConfigDict(extra="ignore")


class FacultyAIReviewInput(BaseModel):
    """Context input payload provided to the AI review pipeline."""

    project_id: uuid.UUID
    project_title: str
    project_description: str
    project_status: str
    team_name: str
    lead_student_name: str | None = None
    repository_url: str | None = None
    problem_title: str
    problem_description: str
    problem_category: str
    problem_location: str | None = None
    problem_district: str | None = None
    updates: list[ProjectUpdateSummary] = Field(default_factory=list)
    previous_reviews: list[ProjectReviewSummary] = Field(default_factory=list)
    member_count: int = 1

    model_config = ConfigDict(extra="ignore")


class FacultyAIReviewOutput(BaseModel):
    """Structured evaluation output generated by Faculty AI Review Assistant."""

    summary: str = Field(
        ...,
        description="Concise academic assessment of current project status and alignment with the civic problem.",
    )
    progress_percentage: int = Field(
        ...,
        ge=0,
        le=100,
        description="Estimated completion percentage based strictly on delivered work and milestone updates.",
    )
    completed_work: list[str] = Field(
        default_factory=list,
        description="Verified tangible engineering outputs, prototypes, or completed milestones.",
    )
    pending_work: list[str] = Field(
        default_factory=list,
        description="Remaining technical components, missing testing, field validation, or documentation.",
    )
    strengths: list[str] = Field(
        default_factory=list,
        description="Notable engineering practices, domain understanding, or proactive team execution.",
    )
    risks: list[str] = Field(
        default_factory=list,
        description="Identified technical, operational, timeline, deployment, or scope risks.",
    )
    suggested_feedback: list[str] = Field(
        default_factory=list,
        description="Actionable, constructive guidance points for the faculty mentor to provide to the team.",
    )
    next_steps: list[str] = Field(
        default_factory=list,
        description="Recommended next research, engineering, field testing, or deployment steps.",
    )
    overall_assessment: Literal["on_track", "needs_attention", "behind", "insufficient_data"] = Field(
        ...,
        description="High-level evaluation verdict: on_track, needs_attention, behind, or insufficient_data.",
    )

    model_config = ConfigDict(extra="ignore")


class FacultyAIReviewResponse(BaseModel):
    """Standard API response wrapper."""

    success: bool = True
    data: FacultyAIReviewOutput

