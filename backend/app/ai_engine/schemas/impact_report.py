"""Pydantic schemas for Admin AI Impact Report Generator.

Defines statistics contracts, LLM structured output schema, and API response contracts.
"""

from typing import Any
from pydantic import BaseModel, ConfigDict, Field


class AdminImpactUserStats(BaseModel):
    total: int = 0
    citizens: int = 0
    students: int = 0
    faculty: int = 0
    universities: int = 0
    industry: int = 0
    admins: int = 0
    active_users: int = 0
    verified_users: int = 0

    model_config = ConfigDict(extra="ignore")


class AdminImpactProblemStats(BaseModel):
    total: int = 0
    approved: int = 0
    pending: int = 0
    rejected: int = 0
    in_progress: int = 0
    resolved: int = 0
    status_breakdown: dict[str, int] = Field(default_factory=dict)

    model_config = ConfigDict(extra="ignore")


class AdminImpactProjectStats(BaseModel):
    total: int = 0
    active: int = 0
    completed: int = 0
    status_breakdown: dict[str, int] = Field(default_factory=dict)

    model_config = ConfigDict(extra="ignore")


class AdminImpactParticipationStats(BaseModel):
    students_engaged: int = 0
    solutions_submitted: int = 0
    updates_posted: int = 0

    model_config = ConfigDict(extra="ignore")


class AdminImpactCategoryItem(BaseModel):
    category: str
    count: int

    model_config = ConfigDict(extra="ignore")


class AdminImpactLocationItem(BaseModel):
    location: str
    count: int

    model_config = ConfigDict(extra="ignore")


class AdminImpactActivityItem(BaseModel):
    action: str
    target_type: str
    timestamp: str

    model_config = ConfigDict(extra="ignore")


class AdminImpactStatistics(BaseModel):
    """Normalized snapshot of verified platform metrics used to drive the AI report."""

    users: AdminImpactUserStats = Field(default_factory=AdminImpactUserStats)
    problems: AdminImpactProblemStats = Field(default_factory=AdminImpactProblemStats)
    projects: AdminImpactProjectStats = Field(default_factory=AdminImpactProjectStats)
    participation: AdminImpactParticipationStats = Field(default_factory=AdminImpactParticipationStats)
    top_categories: list[AdminImpactCategoryItem] = Field(default_factory=list)
    top_locations: list[AdminImpactLocationItem] = Field(default_factory=list)
    recent_activity: list[AdminImpactActivityItem] = Field(default_factory=list)
    period: str = "30d"
    district: str | None = None
    generated_at: str = ""

    model_config = ConfigDict(extra="ignore")


class AdminImpactReportOutput(BaseModel):
    """Structured natural-language evaluation generated by AI Impact Report Generator."""

    headline: str = Field(..., description="Compelling, data-accurate headline summarizing platform impact.")
    executive_summary: str = Field(..., description="Concise executive narrative of platform reach and results.")
    key_achievements: list[str] = Field(
        default_factory=list,
        description="Bullet list of verifiable quantitative and qualitative milestones.",
    )
    problem_impact: str = Field(
        ...,
        description="Assessment of citizen problem reporting, approval rate, and resolution velocity.",
    )
    community_engagement: str = Field(
        ...,
        description="Evaluation of citizen participation, geographical reach, and community trust.",
    )
    student_impact: str = Field(
        ...,
        description="Analysis of student innovation pods, active teams, and engineering output.",
    )
    collaboration_impact: str = Field(
        ...,
        description="Assessment of cross-sector collaboration between citizens, universities, faculty, and industry.",
    )
    key_insights: list[str] = Field(
        default_factory=list,
        description="Strategic observations derived strictly from the statistical distribution.",
    )
    areas_needing_attention: list[str] = Field(
        default_factory=list,
        description="Bottlenecks, pending backlogs, or underserved domains requiring administrative intervention.",
    )
    recommended_next_steps: list[str] = Field(
        default_factory=list,
        description="Actionable policy, outreach, or workflow recommendations for administrators.",
    )
    is_data_limited: bool = Field(
        default=False,
        description="Indicates whether report is operating under low or sparse data limitations.",
    )

    model_config = ConfigDict(extra="ignore")


class AdminImpactReportGenerateRequest(BaseModel):
    """Request payload to generate an impact report."""

    period: str = Field(default="30d", pattern="^(7d|30d|all)$")
    district: str | None = None


class AdminImpactReportResponseData(BaseModel):
    """Data payload returned in API response."""

    report: AdminImpactReportOutput
    statistics: AdminImpactStatistics
    generated_at: str


class AdminImpactReportResponse(BaseModel):
    """Standard API response wrapper."""

    success: bool = True
    data: AdminImpactReportResponseData
    message: str = "AI Impact Report generated successfully."
