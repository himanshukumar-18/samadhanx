"""Model for storing generated Admin AI Impact Reports."""

import uuid
from typing import TYPE_CHECKING
from sqlalchemy import JSON, ForeignKey, String
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import BaseModel

if TYPE_CHECKING:
    from app.models.user import User


class AdminAIImpactReport(BaseModel):
    """
    Persisted AI Impact Report generated by platform administrators.
    Stores snapshot of underlying statistics and structured natural-language evaluation.
    """

    __tablename__ = "admin_ai_impact_reports"

    generated_by_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    period: Mapped[str] = mapped_column(String(20), default="30d", nullable=False)
    district: Mapped[str | None] = mapped_column(String(100), nullable=True, index=True)

    statistics_snapshot: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)
    report_data: Mapped[dict] = mapped_column(JSON, nullable=False, default=dict)

    # Relationship
    generator: Mapped["User | None"] = relationship("User")
